int Calc_Average(int* _value_arr_i, uint8_t _aver_qnt_u8) {
	if (_aver_qnt_u8 <3) return 0;

	for (int q=0; q<_aver_qnt_u8; q++) {
		DBG3("%d  ", (int)_value_arr_i[q]); fflush(stdout);
	}
	DBG3("->  "); fflush(stdout);
	Bubble_sort(_value_arr_i, _aver_qnt_u8);

	for (int q=0; q<_aver_qnt_u8; q++) {
		DBG3("%d  ", (int)_value_arr_i[q]); fflush(stdout);
	}
		//	DBG3("\r\n");
	int rezult_i = 0;
	for (int s=1; s<_aver_qnt_u8-1; s++) {
		rezult_i = rezult_i + _value_arr_i[s];
	}

	rezult_i = rezult_i / (_aver_qnt_u8-2);
	DBG3("Res: %d\r\n", rezult_i);
	return rezult_i;
} //*****************************************************************************

void Bubble_sort(int* _sort_arr_i, uint8_t _sort_qnt_u8) {
	for (int j=0; j<_sort_qnt_u8-1; j++) {
		for (int i=0; i < _sort_qnt_u8-j-1; i++) {
			if (_sort_arr_i[i] > _sort_arr_i[i+1]) {
				int tmp_i = _sort_arr_i[i];
				_sort_arr_i[i] = _sort_arr_i[i+1];
				_sort_arr_i[i+1] = tmp_i;
			}
		}
	}
} //*****************************************************************************

